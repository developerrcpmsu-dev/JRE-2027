/**
 * ตรวจสอบว่ารายการผู้สมัครนี้ตรงกับคณะกรรมการดำเนินงาน 8 ท่านคนใดหรือไม่
 */
export const findMatchingCommitteeMemberSpec = (reg) => {
  if (!reg) return null;
  if (reg.committee_member_key) {
    const byKey = OFFICIAL_8_COMMITTEE_ROSTER.find(c => c.key === reg.committee_member_key);
    if (byKey) return byKey;
  }
  const combinedName = `${reg.first_name || ''} ${reg.last_name || ''} ${reg.full_name_affiliation || ''}`
    .replace(/\s+/g, ' ')
    .trim();
  if (!combinedName) return null;

  for (const spec of OFFICIAL_8_COMMITTEE_ROSTER) {
    const fullTarget = `${spec.first_name} ${spec.last_name}`.trim();
    if (fullTarget && combinedName.includes(fullTarget)) {
      return spec;
    }
    if (Array.isArray(spec.matchTokens)) {
      for (const token of spec.matchTokens) {
        if (token && token.length >= 4 && combinedName.includes(token)) {
          // ถ้าระบุแค่นามต้น เช่น ณัฐพล หรือ วรภัทร ให้เช็คด้วยว่านามสกุลไม่ขัดแย้งกัน (หรือไม่มีนามสกุลอื่น)
          if (!spec.last_name || !reg.last_name || String(reg.last_name).includes(spec.last_name.slice(0, 3))) {
            return spec;
          }
        }
      }
    }
  }
  return null;
};

/**
 * ค้นหาว่าคณะกรรมการดำเนินงานท่านนี้มีรายชื่ออยู่ใน registrations แล้วหรือยัง (เพื่อป้องกันการสร้างซ้ำ 100%)
 */
export const findExistingRegForCommitteeSpec = (registrations = [], spec) => {
  if (!spec || !Array.isArray(registrations)) return null;
  // 1. ค้นหาจาก committee_member_key หรือ user_id ที่ตรงกัน
  const byKey = registrations.find(r => r && (r.committee_member_key === spec.key || r.user_id === `staff_${spec.key}`));
  if (byKey) return byKey;

  // 2. ค้นหาจากชื่อ-นามสกุลจริงในระบบ
  const fullTarget = `${spec.first_name} ${spec.last_name}`.trim();
  for (const r of registrations) {
    if (!r) continue;
    const rName = `${r.first_name || ''} ${r.last_name || ''} ${r.full_name_affiliation || ''}`
      .replace(/\s+/g, ' ')
      .trim();
    if (fullTarget && rName.includes(fullTarget)) {
      return r;
    }
    if (Array.isArray(spec.matchTokens)) {
      for (const token of spec.matchTokens) {
        if (token && rName.includes(token)) {
          if (!spec.last_name || !r.last_name || String(r.last_name).includes(spec.last_name.slice(0, 3))) {
            return r;
          }
        }
      }
    }
  }
  return null;
};

/**
 * ดึงหมายเหตุหน้าที่รับผิดชอบของคณะกรรมการ/Staff หรือผู้เข้าร่วม ("คือใคร ทำอะไร")
 */
export const resolveCommitteeDutyNote = (reg) => {
  if (!reg) return '';
  if (reg.committee_duty_note && String(reg.committee_duty_note).trim() !== '') {
    return String(reg.committee_duty_note).trim();
  }
  const matchedSpec = findMatchingCommitteeMemberSpec(reg);
  if (matchedSpec && matchedSpec.committee_duty_note) {
    return matchedSpec.committee_duty_note;
  }
  if (isStaffRegistration(reg)) {
    const roleType = resolveStaffRoleType(reg);
    if (roleType === 'dev') return 'คณะทำงาน • ผู้พัฒนาระบบ (Dev / Staff)';
    if (roleType === 'mc') return 'คณะกรรมการดำเนินงาน • พิธีกรดำเนินรายการ (MC)';
    if (roleType === 'photographer') return 'คณะกรรมการดำเนินงาน • ช่างภาพและสื่อโสตทัศนูปกรณ์';
    if (roleType === 'committee') return 'คณะกรรมการดำเนินงาน (Organizing Committee)';
    return 'สตาฟโครงการ (Project Staff)';
  }
  return '';
};

export const resolveStaffRoleType = (rawReg) => {
  if (!rawReg) return 'participant';
  let extra = {};
  if (rawReg?.special_notes && typeof rawReg.special_notes === 'string' && rawReg.special_notes.startsWith('{')) {
    try { extra = JSON.parse(rawReg.special_notes); } catch (e) {}
  } else if (rawReg?.special_notes && typeof rawReg.special_notes === 'object') {
    extra = rawReg.special_notes;
  }
  const reg = { ...extra, ...rawReg };
  if (reg.admin_staff_override === false) return 'participant';
  if (reg.staff_role_type && reg.staff_role_type !== 'participant') return reg.staff_role_type;
  const fullNameStr = `${reg.first_name || ''} ${reg.last_name || ''} ${reg.full_name_affiliation || ''}`;
  for (const item of OFFICIAL_COMMITTEE_NAMES) {
    if (fullNameStr.includes(item.match)) {
      return item.role;
    }
  }
  const unitStr = `${reg.unit || ''} ${reg.callsign || ''}`.toLowerCase();
  if (unitStr.includes('ช่างภาพ')) return 'photographer';
  if (unitStr.includes('พิธีกร')) return 'mc';
  if (unitStr.includes('dev')) return 'dev';
  return isStaffRegistration(reg) ? 'committee' : 'participant';
};

/**
 * ตรวจสอบว่าผู้สมัครเป็น Staff โครงการ (โอน 280 บาท ค่าเสื้อ หรือหมายเหตุเป็น (STAFF) แม้โอนเกิน) หรือไม่
 * รองรับทั้งการติ๊กเลือก is_staff, การเลือกผ่าน Dropdown ของ Admin/Dev, รายชื่อคณะกรรมการดำเนินงาน 14 ท่าน และการตรวจจับอัตโนมัติจากยอดโอน 280 บาท
 */
export const isStaffRegistration = (rawReg) => {
  if (!rawReg) return false;
  if (typeof rawReg === 'boolean') return rawReg;
  let extra = {};
  if (rawReg?.special_notes && typeof rawReg.special_notes === 'string' && rawReg.special_notes.startsWith('{')) {
    try { extra = JSON.parse(rawReg.special_notes); } catch (e) {}
  } else if (rawReg?.special_notes && typeof rawReg.special_notes === 'object') {
    extra = rawReg.special_notes;
  }
  const reg = { ...extra, ...rawReg };
  if (reg.admin_staff_override === false) return false;
  if (reg.admin_staff_override === true || reg.is_staff === true || reg.is_staff === 'true') return true;
  if (reg.staff_role_type && reg.staff_role_type !== 'participant') return true;
  if (reg.registration_type === 'staff' || reg.applicant_role === 'staff' || reg.payment_plan === 'staff') return true;

  // ตรวจจากรายชื่อคณะกรรมการดำเนินงานอย่างเป็นทางการ + ผู้พัฒนาระบบ
  const fullNameStr = `${reg.first_name || ''} ${reg.last_name || ''} ${reg.full_name_affiliation || ''}`;
  if (OFFICIAL_COMMITTEE_NAMES.some(item => fullNameStr.includes(item.match))) {
    return true;
  }

  // ตรวจจากรหัสนามเรียกขาน ชื่อ หรือชื่อเล่นที่มีคำว่า (STAFF) / STAFF / สตาฟ
  const callsignAndNameStr = `${reg.callsign || ''} ${reg.full_name_affiliation || ''} ${reg.nickname || ''}`.toLowerCase();
  if (callsignAndNameStr.includes('staff') || callsignAndNameStr.includes('สตาฟ')) {
    return true;
  }

  // ตรวจจากยอดสลิป OCR หรือยอดเงินที่บันทึกว่าเป็น 280 บาท (ค่าเสื้อ Staff) หรือ 480 บาท (ค่าเสื้อ 280 + ค่าที่พัก Staff ต่างมหาลัย 200)
  const ocrFullAmt = Number(reg.slip_ocr_full?.amount || 0);
  const ocrR1Amt = Number(reg.slip_ocr_round1?.amount || 0);
  const paymentAmt = Number(reg.payment_amount || 0);
  if (Math.abs(ocrFullAmt - STAFF_SHIRT_FEE) <= 0.01 || Math.abs(ocrFullAmt - STAFF_EXTERNAL_TOTAL_FEE) <= 0.01) return true;
  if (Math.abs(ocrR1Amt - STAFF_SHIRT_FEE) <= 0.01 || Math.abs(ocrR1Amt - STAFF_EXTERNAL_TOTAL_FEE) <= 0.01) return true;
  if (Math.abs(paymentAmt - STAFF_SHIRT_FEE) <= 0.01 || Math.abs(paymentAmt - STAFF_EXTERNAL_TOTAL_FEE) <= 0.01) return true;

  // ตรวจจากหมายเหตุการโอนเงินและหมายเหตุแอดมิน (รองรับกรณีจ่ายเกินมาแต่แอดมินหมายเหตุว่า (STAFF))
  const safeSpecialNotes = (reg.special_notes && !String(reg.special_notes).trim().startsWith('{') && !String(reg.special_notes).startsWith('__JSON__:'))
    ? reg.special_notes
    : (reg.user_notes || '');
  const notesStr = `${reg.payment_notes || ''} ${reg.installment_1_notes || ''} ${safeSpecialNotes} ${reg.admin_private_notes || ''}`.toLowerCase();
  if (
    notesStr.includes('(staff)') ||
    notesStr.includes('[staff]') ||
    notesStr.includes('เป็น staff') ||
    notesStr.includes('ค่าเสื้อ staff') ||
    notesStr.includes('สตาฟ') ||
    (notesStr.includes('staff') && (notesStr.includes('280') || notesStr.includes('480')))
  ) {
    return true;
  }

  return false;
};

/**
 * จัดรูปแบบนามเรียกขานให้อ่านง่าย มีการเว้นวรรคระหว่างอักษรย่อกับตัวเลข เช่น TSI2121 -> TSI 2121, RCP16-37 -> RCP 16-37
 */
export const normalizeCallsignSpacing = (callsign = '') => {
  if (!callsign) return '';
  let str = String(callsign).trim();
  // เว้นวรรค TSI / RCP กับตัวเลข เช่น TSI2121 -> TSI 2121, RCP16-37 -> RCP 16-37
  str = str.replace(/\b(TSI|RCP)\s*([0-9])/gi, (_, prefix, num) => `${prefix.toUpperCase()} ${num}`);
  str = str.replace(/\s+/g, ' ');
  return str;
};

/**
 * จัดรูปแบบนามเรียกขานให้มีคำว่า (STAFF) ต่อท้ายเสมอหากเป็น Staff (หรือลบออกหากยกเลิก Staff)
 */
export const formatStaffCallsign = (rawCallsign = '', shouldBeStaff = false) => {
  let cleaned = String(rawCallsign || '')
    .replace(/\s*\(\s*dev\s*\/\s*staff\s*\)/gi, '')
    .replace(/\s*\(\s*staff\s*\)/gi, '')
    .replace(/\s*\[\s*staff\s*\]/gi, '')
    .trim();
  cleaned = normalizeCallsignSpacing(cleaned);
  if (!shouldBeStaff) return cleaned;
  return cleaned ? `${cleaned} (STAFF)` : '(STAFF)';
};

/**
 * จำแนกประเภท/บทบาทของผู้เข้าร่วมโครงการอย่างชัดเจน (Category Resolver):
 * 1. committee: คณะกรรมการดำเนินงานโครงการ
 * 2. staff: Staff ทีมงาน (MC, ช่างภาพ, สื่อโสตฯ, Dev, สตาฟ)
 * 3. club_org: ชมรม / หน่วยงาน (ชมรมกู้ภัยราชพฤกษ์ มมส (RCP), ชมรม TSI มข, หน่วยกู้ภัย)
 * 4. volunteer: นิสิตอาสา (จิตอาสา มข/มมส)
 * 5. participant: ผู้เข้าอบรมทั่วไป
 */
export const getParticipantCategory = (itemOrReg) => {
  if (!itemOrReg) return 'participant';
  const reg = itemOrReg.reg || itemOrReg;
  let sn = {};
  try {
    sn = typeof reg.special_notes === 'string' ? JSON.parse(reg.special_notes) : (reg.special_notes || {});
  } catch (e) {
    sn = {};
  }
  const staffRoleType = itemOrReg.staffRoleType || reg.staff_role_type || sn.staff_role_type;
  const duty = String(itemOrReg.dutyNote || reg.committee_duty_note || sn.committee_duty_note || '');
  const cs = normalizeCallsignSpacing(reg.callsign || itemOrReg.callsign || sn.callsign || '');
  const isCommitteeSpec = Boolean(
    itemOrReg.committeeSpec ||
    itemOrReg.isCommitteeSpec ||
    reg.committee_member_key ||
    sn.committee_member_key ||
    (reg.user_id && String(reg.user_id).startsWith('staff_committee_'))
  );

  // 1. Explicit Overrides
  if (staffRoleType === 'volunteer') return 'volunteer';
  if (staffRoleType === 'club_org') return 'club_org';
  if (staffRoleType === 'committee') return 'committee';

  // 2. Staff: MC, Photographer, Dev, Explicit Staff
  if (
    ['staff', 'mc', 'photographer', 'dev'].includes(staffRoleType) ||
    duty.includes('สตาฟ') ||
    duty.includes('Staff') ||
    duty.includes('พิธีกร') ||
    duty.includes('ช่างภาพ') ||
    duty.includes('โสต') ||
    duty.includes('ผู้พัฒนาระบบ') ||
    duty.includes('ฝ่ายเทคโนโลยี') ||
    /^(MC|17-02)/i.test(cs) ||
    (cs.includes('(STAFF)') && (cs.includes('MC') || cs.includes('17-02') || cs.includes('DEV')))
  ) {
    return 'staff';
  }

  // 3. Committee: Organizing Committee
  if (
    isCommitteeSpec ||
    duty.includes('คณะกรรมการ')
  ) {
    return 'committee';
  }

  // 4. Volunteer: นิสิตจิตอาสา
  if (
    /^อาสา/i.test(cs) ||
    cs.includes('อาสา') ||
    duty.includes('อาสา') ||
    (reg.unit && reg.unit.includes('อาสา')) ||
    (reg.institution && reg.institution.includes('อาสา'))
  ) {
    return 'volunteer';
  }

  // 5. Club / Organization: RCP / TSI / สังกัดชมรม
  if (
    /^(RCP|TSI)/i.test(cs) ||
    (reg.unit && (reg.unit.includes('ชมรม') || reg.unit.includes('กู้ภัย'))) ||
    (reg.institution && (reg.institution.includes('ชมรม') || reg.institution.includes('กู้ภัย')))
  ) {
    return 'club_org';
  }

  return 'participant';
};

/**
 * ลำดับการเรียงเริ่มต้นของตารางสรุปยอดและรายชื่อสำรวจการเข้าร่วม (JRE 2027 Roster Sort)
 * Tier 1: คณะกรรมการ มมส (ชาย -> หญิง)
 * Tier 2: คณะกรรมการ มข (ชาย -> หญิง)
 * Tier 3: Staff ทีมงาน (MC, ช่างภาพ, Dev, สตาฟ) (ชาย -> หญิง)
 * Tier 4: สมาชิกชมรมกู้ภัยราชพฤกษ์ มมส (RCP) (ชาย -> หญิง)
 * Tier 5: สมาชิกชมรม TSI มข (ชาย -> หญิง)
 * Tier 6: นิสิตอาสาของทาง มข (ชาย -> หญิง)
 * Tier 7: ผู้เข้าร่วมสถาบันอื่นๆ / ผู้เข้าอบรมทั่วไป (ชาย -> หญิง)
 */
export const getRosterSortTier = (item) => {
  if (!item) return 99;
  const reg = item.reg || item;
  const isMsu = item.uniInfo?.isMsu || item.uniInfo?.shortTag === 'มมส' || (reg?.institution || '').includes('มหาสารคาม') || (reg?.user_id || '').includes('msu');
  const isKku = item.uniInfo?.shortTag === 'มข' || (reg?.institution || '').includes('ขอนแก่น') || (reg?.user_id || '').includes('kku');
  const cat = getParticipantCategory(item);

  // 1. คณะกรรมการ มมส
  if (cat === 'committee' && isMsu) return 1;
  // 2. คณะกรรมการ มข
  if (cat === 'committee' && isKku) return 2;
  // 3. Staff ทีมงาน (MC, ช่างภาพ, Dev, สตาฟ)
  if (cat === 'staff') return 3;
  // 4. สมาชิกชมรมกู้ภัยราชพฤกษ์ มมส (RCP)
  if (cat === 'club_org' && isMsu) return 4;
  // 5. สมาชิกชมรม TSI มข
  if (cat === 'club_org' && isKku) return 5;
  // 6. นิสิตอาสาของทาง มข
  if (cat === 'volunteer') return 6;
  // 7. ผู้เข้าร่วมสถาบันอื่นๆ / ผู้เข้าอบรมทั่วไป
  return 7;
};

export const compareRosterItems = (a, b) => {
  const tierA = getRosterSortTier(a);
  const tierB = getRosterSortTier(b);
  if (tierA !== tierB) return tierA - tierB;

  // เรียงแยก ชาย -> หญิง
  const genderWeightA = a.gender === 'ชาย' ? 0 : 1;
  const genderWeightB = b.gender === 'ชาย' ? 0 : 1;
  if (genderWeightA !== genderWeightB) return genderWeightA - genderWeightB;

  // ถ้า tier และเพศเดียวกัน ให้เรียงตาม committee order (ถ้ามี)
  const orderA = a.committeeSpec?.order ?? 999;
  const orderB = b.committeeSpec?.order ?? 999;
  if (orderA !== orderB) return orderA - orderB;

  // เรียงตามนามเรียกขาน (ถ้ามี)
  const csA = normalizeCallsignSpacing(a.reg?.callsign || '');
  const csB = normalizeCallsignSpacing(b.reg?.callsign || '');
  if (csA && csB && csA !== csB) return csA.localeCompare(csB, 'th');

  // เรียงตามชื่อ-นามสกุล
  return (a.fullName || '').localeCompare(b.fullName || '', 'th');
};

